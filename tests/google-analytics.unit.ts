import { test } from 'node:test';
import assert from 'node:assert/strict';
import { analyticsAllowed, enableGoogleAnalytics, disableGoogleAnalytics, trackGoogleTool, GA_MEASUREMENT_ID } from '../src/lib/google-analytics';

test('Google Analytics loads only with consent, once, and stops after withdrawal', () => {
  let consent: string | null = null;
  const scripts: unknown[] = [];
  const win: Record<string, unknown> = {};
  Object.defineProperty(globalThis, 'window', { configurable: true, value: win });
  Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { doNotTrack: '0', globalPrivacyControl: false } });
  Object.defineProperty(globalThis, 'localStorage', { configurable: true, value: { getItem: () => consent } });
  Object.defineProperty(globalThis, 'location', { configurable: true, value: { pathname: '/', hostname: 'informersidea.com' } });
  Object.defineProperty(globalThis, 'document', { configurable: true, value: { cookie: '', createElement: () => ({}), head: { appendChild: (script: unknown) => scripts.push(script) } } });
  enableGoogleAnalytics();
  assert.equal(scripts.length, 0);
  consent = 'no';
  enableGoogleAnalytics();
  assert.equal(scripts.length, 0);
  consent = 'yes';
  Object.assign(navigator, { doNotTrack: '1' });
  assert.equal(analyticsAllowed(), false);
  enableGoogleAnalytics();
  Object.assign(navigator, { doNotTrack: '0', globalPrivacyControl: true });
  enableGoogleAnalytics();
  assert.equal(scripts.length, 0);
  Object.assign(navigator, { globalPrivacyControl: false });
  location.pathname = '/admin';
  enableGoogleAnalytics();
  assert.equal(scripts.length, 0);
  location.pathname = '/';
  enableGoogleAnalytics();
  enableGoogleAnalytics();
  assert.equal(scripts.length, 1);
  const commands = () => (win.dataLayer as ArrayLike<unknown>[]).map((command) => Array.from(command));
  assert.equal(commands().filter((command) => command[0] === 'config').length, 1);
  assert.equal(commands().some((command) => command[1] === 'page_view'), false);
  trackGoogleTool('compress-image');
  assert.deepEqual(commands().at(-1), ['event', 'tool_started', { tool_id: 'compress-image' }]);
  const count = commands().length;
  trackGoogleTool('private file.pdf');
  assert.equal(commands().length, count);
  disableGoogleAnalytics();
  assert.equal(win[`ga-disable-${GA_MEASUREMENT_ID}`], true);
  trackGoogleTool('compress-image');
  assert.equal(commands().length, count);
  consent = 'no';
  enableGoogleAnalytics();
  assert.equal(win[`ga-disable-${GA_MEASUREMENT_ID}`], true);
});
